/**
 * `@adi/workflows` — what a workflow file (`workflows/*.ts`, `projects/<id>/workflows/*.ts`)
 * imports to declare *when* it runs (`schedule`/`event`/`manual`) and to drive its own body
 * through durable checkpoints (`createCtx`'s `ctx`). Seeded into the mono store's own
 * `node_modules`, the same way `@adi/db` is, so every workflow file resolves it with no install
 * step.
 *
 * ```ts
 * import { z } from "zod";
 * import { schedule, workflow } from "@adi/workflows";
 *
 * export const on = schedule("0 5 * * MON", "America/New_York");
 * export const input = z.object({ topic: z.string() });
 * export const output = z.object({ posted: z.boolean() });
 *
 * export default workflow(async (ctx, input) => {
 *   const draft = await ctx.step({ key: "draft", fn: () => writeDraft(input.topic) });
 *   await ctx.task({ key: "review", person: "igor", instructions: "approve?", input: draft,
 *                    output: z.object({ approved: z.boolean() }) });
 *   return { posted: true };
 * });
 * ```
 *
 * Two very different processes import this same file: `adi-workflows`' `describe` harness (just
 * to read `on`/`input`/`output` back as JSON — it never calls `workflow(...)`'s function) and its
 * `run` harness (one `bun` process per *attempt*, spawned by the Rust host, not detached — see
 * `createCtx`'s own doc for the wire protocol between them). `workflow()` itself stays a thin
 * marker either way: the engine decides whether today's import is a describe or a run, not this
 * file.
 *
 * Generated by the platform from `crates/adi-workflows/templates/client/index.ts`; local edits are
 * overwritten on the next start.
 */

import { type ZodType, z } from "zod";

/** `catchUp` option on a [`schedule`] trigger — see spec section D. */
export type CatchUp = "fire" | "skip";

/** A workflow started by a cron rule in its own IANA timezone. */
export interface ScheduleTrigger {
  type: "schedule";
  /** Standard 5-field unix cron (`min hour dom month dow`) — e.g. `"0 5 * * MON"`. The engine
   * normalizes this into its own 6-field dialect; write it the way `crontab` would. */
  cron: string;
  /** An IANA zone name (`"America/New_York"`), never a bare offset. */
  tz: string;
  catchUp?: CatchUp;
}

/** A workflow started by a matching platform event. */
export interface EventTrigger {
  type: "event";
  /** A dotted event pattern (`"adi.tasks.*"`) — segment globs, same as a trigger's `trigger_on`. */
  pattern: string;
  /** Every key here must equal the same field in the matched event's JSON payload. Omit to match
   * on the pattern alone. */
  where?: Record<string, unknown>;
}

/** A workflow started only by an explicit `adi-mono workflows run` (or the panel's ▶ Run). */
export interface ManualTrigger {
  type: "manual";
}

export type Trigger = ScheduleTrigger | EventTrigger | ManualTrigger;

/** `on: schedule(cron, tz)` — see [`ScheduleTrigger`] for the cron dialect this expects. */
export function schedule(cron: string, tz: string, opts?: { catchUp?: CatchUp }): ScheduleTrigger {
  return { type: "schedule", cron, tz, catchUp: opts?.catchUp ?? "fire" };
}

/** `on: event(pattern, where?)` — see [`EventTrigger`]. */
export function event(pattern: string, where?: Record<string, unknown>): EventTrigger {
  return { type: "event", pattern, where };
}

/** `on: manual()` — a workflow with no automatic starter at all. */
export function manual(): ManualTrigger {
  return { type: "manual" };
}

/** A workflow's `ctx` parameter — every building block spec section E lists. */
export interface Ctx {
  /**
   * Run `fn` once and remember its return value. `fn` may run more than once if the process
   * crashes after it took effect but before the result was saved — the docs (`guides/
   * workflows.md`) teach check-before-act / dedupe keys for exactly this reason. Prefer `ctx.task`
   * when the effect is "ask an agent or a person", since a task is itself idempotent by
   * construction (its own `stepId`); reach for `ctx.step` for a plain computation or an API call.
   */
  step<T>(opts: { key: string; fn: () => T | Promise<T>; retry?: number }): Promise<T>;
  /**
   * Create a real task (once, by `stepId`) and wait for it. Resolves to the validated result, or
   * `{ timed_out: true }` once `timeout` (milliseconds) elapses with the task still open — never
   * validated against `output`, since it isn't that shape. Throws [`TaskGaveUp`] if the task's
   * assignee gave up on it.
   */
  task<Out>(opts: {
    key: string;
    title: string;
    agent?: string;
    person?: string;
    instructions?: string;
    input?: unknown;
    output?: ZodType<Out>;
    timeout?: number;
    project?: string;
    cwd?: string;
  }): Promise<Out | { timed_out: true }>;
  /** Start (once, by key) a child run of `workflow` and wait for its own output. */
  run<Out>(opts: { key: string; workflow: string; input?: unknown }): Promise<Out>;
  /**
   * Wait for the first event matching `event` (and `where`, if given) emitted *after* this step
   * was first reached — not before, and not every later match, just the first. Resolves to its
   * JSON payload, or `{ timed_out: true }` once `timeout` (milliseconds) elapses.
   */
  waitFor<T = unknown>(opts: {
    key: string;
    event: string;
    where?: Record<string, unknown>;
    timeout?: number;
  }): Promise<T | { timed_out: true }>;
  /** Wait until `until` (epoch milliseconds, or anything `Date` parses). */
  sleep(opts: { key: string; until: number | string | Date }): Promise<void>;
  /**
   * Ask `person` something and wait for an answer — a lighter-weight `ctx.task` for a person
   * assignee with no particular output shape; resolves to whatever they completed it with (or
   * `null`). Also raises a notification Ask — WF-6's job to wire up, not this engine's.
   */
  ask(opts: { key: string; person: string; text: string }): Promise<unknown>;
  /** This run's own working directory — where a step too big for the journal (>256 KB JSON) goes
   * on disk, with just its path saved instead. */
  readonly dir: string;
  readonly runId: string;
  /** The schedule slot this run fired for (`ScheduleTrigger`'s own ISO timestamp), or `""` for a
   * run that didn't start from a schedule. */
  readonly slot: string;
}

/** Thrown by `ctx.task`/`ctx.run`/`ctx.ask` when the underlying task's assignee gave up on it. A
 * workflow that never catches this ends its *run* in failure — the engine's own top-level catch,
 * not this class, is what does that. */
export class TaskGaveUp extends Error {
  readonly reason: string;
  constructor(reason: string) {
    super(`task given up on: ${reason}`);
    this.name = "TaskGaveUp";
    this.reason = reason;
  }
}

/** Thrown internally by every `ctx` checkpoint that has nothing resolved yet. The run harness's
 * own top-level `catch` is the only thing that should ever see one — it means "nothing further
 * this attempt", not an error in the workflow. Exported only so that harness (a different file,
 * `run.ts`, importing this same package) can `instanceof` it. */
export class Suspend extends Error {
  constructor() {
    super("workflow suspended: a checkpoint has nothing resolved yet");
    this.name = "Suspend";
  }
}

/** One line of newline-delimited JSON read from the host, lazily — nothing here touches stdin
 * until a `ctx` checkpoint actually awaits one, so importing this module to merely `describe` a
 * workflow file (stdin closed, never read) never blocks on it. */
async function* readLines(): AsyncGenerator<string> {
  const reader = Bun.stdin.stream().getReader();
  const decoder = new TextDecoder();
  let buffer = "";
  while (true) {
    const { done, value } = await reader.read();
    if (done) break;
    buffer += decoder.decode(value, { stream: true });
    let newline: number;
    while ((newline = buffer.indexOf("\n")) >= 0) {
      yield buffer.slice(0, newline);
      buffer = buffer.slice(newline + 1);
    }
  }
}

/** The arguments every `ctx` checkpoint call is fully determined by. */
export function createCtx(opts: { runId: string; dir: string; slot: string }): Ctx {
  const lines = readLines();
  const seen = new Set<string>();

  function claim(key: string): void {
    if (key === "_root") {
      throw new Error('step key "_root" is reserved for the run\'s own root task');
    }
    if (seen.has(key)) {
      throw new Error(`duplicate step key ${JSON.stringify(key)} within this run`);
    }
    seen.add(key);
  }

  /** Write one JSON request, read one JSON reply — the whole wire protocol. `ctx` calls are
   * expected to run one at a time (never `Promise.all([ctx.task(...), ctx.task(...)])`); this
   * does not multiplex, by design — a workflow with two independent checkpoints runs them in
   * two separate `await`s, which replay handles exactly as well. */
  async function rpc(request: Record<string, unknown>): Promise<Record<string, unknown>> {
    process.stdout.write(`${JSON.stringify(request)}\n`);
    const { value, done } = await lines.next();
    if (done) {
      throw new Error("the host closed its side of the connection before replying");
    }
    return JSON.parse(value) as Record<string, unknown>;
  }

  /** The `ok`/`pending`/`gave_up`/`timed_out` reply shape `task`/`run`/`ask` all share. */
  async function resolveTaskLike<Out>(
    reply: Record<string, unknown>,
    output?: ZodType<Out>,
  ): Promise<Out | { timed_out: true }> {
    switch (reply.state) {
      case "ok": {
        if (!output) return reply.value as Out;
        const parsed = output.safeParse(reply.value);
        if (!parsed.success) {
          throw new Error(`result did not match the declared output shape: ${parsed.error}`);
        }
        return parsed.data;
      }
      case "timed_out":
        return { timed_out: true };
      case "gave_up":
        throw new TaskGaveUp(typeof reply.reason === "string" ? reply.reason : "");
      default:
        throw new Suspend();
    }
  }

  return {
    dir: opts.dir,
    runId: opts.runId,
    slot: opts.slot,

    async step({ key, fn, retry }) {
      claim(key);
      const check = await rpc({ type: "step", key });
      if (check.cached) return check.value;
      const retries = retry ?? 0;
      let lastError: unknown;
      for (let attempt = 0; attempt <= retries; attempt++) {
        try {
          const value = await fn();
          await rpc({ type: "step_save", key, value });
          return value;
        } catch (err) {
          lastError = err;
        }
      }
      throw lastError;
    },

    async task({ key, title, agent, person, instructions, input, output, timeout, project, cwd }) {
      claim(key);
      const outputSchema = output ? z.toJSONSchema(output) : undefined;
      const reply = await rpc({
        type: "task",
        key,
        title,
        agent,
        person,
        instructions,
        input,
        outputSchema,
        timeoutMs: timeout,
        project,
        cwd,
      });
      return resolveTaskLike(reply, output);
    },

    async run({ key, workflow, input }) {
      claim(key);
      const reply = await rpc({ type: "run", key, workflow, input });
      // `ctx.run` has no `timeout`, so its reply is never `"timed_out"` — the cast just drops
      // `resolveTaskLike`'s wider return type back to the plain `Out` this signature promises.
      const resolved = await resolveTaskLike(reply);
      return resolved;
    },

    async waitFor({ key, event, where, timeout }) {
      claim(key);
      const reply = await rpc({ type: "waitFor", key, event, where, timeoutMs: timeout });
      if (reply.state === "ok") return reply.value;
      if (reply.state === "timed_out") return { timed_out: true };
      throw new Suspend();
    },

    async sleep({ key, until }) {
      claim(key);
      const untilMs = until instanceof Date ? until.getTime() : new Date(until).getTime();
      const reply = await rpc({ type: "sleep", key, until: untilMs });
      if (reply.state === "ok") return;
      throw new Suspend();
    },

    async ask({ key, person, text }) {
      claim(key);
      const reply = await rpc({ type: "ask", key, person, text });
      return resolveTaskLike(reply);
    },
  };
}

/**
 * Wrap a workflow's body — `fn` is called once per attempt, from the top, by the engine's own
 * `run` harness (`createCtx`'s doc has the wire protocol it drives `ctx` through). A resumed run
 * replays every already-journaled checkpoint instantly; only the first not-yet-resolved one
 * actually waits.
 */
export function workflow<Input, Output>(
  fn: (ctx: Ctx, input: Input) => Promise<Output>,
): { readonly __adiWorkflow: true; readonly run: typeof fn } {
  return { __adiWorkflow: true, run: fn };
}
