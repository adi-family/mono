/**
 * `@adi/workflows` — what a workflow file (`workflows/*.ts`, `projects/<id>/workflows/*.ts`)
 * imports to declare *when* it runs. Seeded into the mono store's own `node_modules`, the same way
 * `@adi/db` is, so every workflow file resolves it with no install step.
 *
 * ```ts
 * import { schedule, workflow } from "@adi/workflows";
 *
 * export const on = schedule("0 5 * * MON", "America/New_York");
 *
 * export default workflow(async (ctx, input) => {
 *   // ...
 * });
 * ```
 *
 * **This build only reads `on`.** The engine imports a workflow file to discover its triggers
 * (`adi-workflows`' Rust-side `describe` harness) and, for a schedule or event match, starts a
 * real run — but nothing yet drives the function `workflow()` wraps through its `ctx` checkpoints
 * (`ctx.step`/`ctx.task`/`ctx.run`/`ctx.waitFor`/`ctx.sleep`/`ctx.ask`), replay, or rewind. That is
 * further WORKFLOWS work (ADI-MONO-146 continues); `workflow()` here is a placeholder that lets a
 * file written against the full spec still *declare* itself and be discovered today, with its
 * function body left for the engine to call once it exists.
 *
 * Generated by the platform from `crates/adi-workflows/templates/client/index.ts`; local edits are
 * overwritten on the next start.
 */

/** `catchUp` option on a [`schedule`] trigger — see spec section D. */
export type CatchUp = "fire" | "skip";

/** A workflow started by a cron rule in its own IANA timezone. */
export interface ScheduleTrigger {
  type: "schedule";
  /** Standard 5-field unix cron (`min hour dom month dow`) — e.g. `"0 5 * * MON"`. The engine
   * normalizes this into its own 6-field dialect; write it the way `crontab` would. */
  cron: string;
  /** An IANA zone name (`"America/New_York"`), never a bare offset. */
  tz: string;
  catchUp?: CatchUp;
}

/** A workflow started by a matching platform event. */
export interface EventTrigger {
  type: "event";
  /** A dotted event pattern (`"adi.tasks.*"`) — segment globs, same as a trigger's `trigger_on`. */
  pattern: string;
  /** Every key here must equal the same field in the matched event's JSON payload. Omit to match
   * on the pattern alone. */
  where?: Record<string, unknown>;
}

/** A workflow started only by an explicit `adi-mono workflows run` (or the panel's ▶ Run). */
export interface ManualTrigger {
  type: "manual";
}

export type Trigger = ScheduleTrigger | EventTrigger | ManualTrigger;

/** `on: schedule(cron, tz)` — see [`ScheduleTrigger`] for the cron dialect this expects. */
export function schedule(cron: string, tz: string, opts?: { catchUp?: CatchUp }): ScheduleTrigger {
  return { type: "schedule", cron, tz, catchUp: opts?.catchUp ?? "fire" };
}

/** `on: event(pattern, where?)` — see [`EventTrigger`]. */
export function event(pattern: string, where?: Record<string, unknown>): EventTrigger {
  return { type: "event", pattern, where };
}

/** `on: manual()` — a workflow with no automatic starter at all. */
export function manual(): ManualTrigger {
  return { type: "manual" };
}

/**
 * Wrap a workflow's body. **Not yet called by anything** — see the module header. Kept so a file
 * written against the full spec type-checks and can be discovered (its `on` export read) today.
 */
export function workflow<Input, Output>(
  fn: (ctx: unknown, input: Input) => Promise<Output>,
): { readonly __adiWorkflow: true; readonly run: typeof fn } {
  return { __adiWorkflow: true, run: fn };
}
