//! The device→session-key seal a BYO-credentials unlock uses to carry an unwrapped value from a
//! device to `adi-app`'s in-memory lease table (`docs/byo-credentials.md` §8, §9,
//! ADI-MONO-180 P2.3).
//!
//! QUIC already encrypts the mesh hop end to end, and the local gateway forward is plain HTTP
//! inside that tunnel (`docs/fleet.md` §9) — but a value's nonce/ciphertext still sits in a
//! request body that *could* be logged by something on the way, and a symmetric key fetched over
//! the open `GET /api/leases/session` call would be exactly as exposed as the value it's meant
//! to protect. So this is a fresh ECDH per unlock: the device never learns `adi-app`'s long-term
//! anything (there is no long-term key — see below), and `adi-app` never learns anything it could
//! use to open a *future* unlock it wasn't given the device's half of.
//!
//! * **The session key is ephemeral per process boot, not per call** (`docs/byo-credentials.md`
//!   §9 Q9, settled by this implementation): `adi-app` mints one [`SessionKey`] at startup and
//!   never writes it down, so a restart makes every earlier unlock's binding void — which is
//!   exactly the "a server restart drops every lease" rule §9 already states, extended to the
//!   wire-crypto key that feeds it. [`SessionKey::epoch`] is what lets a device's renew loop tell
//!   the two apart without guessing from a dropped connection.
//! * **The device's own half is a fresh keypair per unlock call**, generated by [`seal`] and
//!   never reused — the usual "ephemeral-ephemeral" ECDH shape, so a seized device after an
//!   unlock has completed cannot be used to re-derive that unlock's key.
//! * **The AAD is the binding, not a secret.** `user:<u>/<NAME>|<epoch>|<device>` names exactly
//!   what this ciphertext may be opened as; mismatching any one component — the wrong user
//!   claiming someone else's lease, a stale epoch from before a restart, or a device the AAD
//!   wasn't built for — fails to decrypt rather than silently opening as the wrong thing. This
//!   module takes the finished AAD string as a parameter; building it (`docs/byo-credentials.md`
//!   §9 step 4: "checks AAD user == header user") is the caller's job, because only the caller
//!   knows which header to trust.

use base64::Engine as _;
use chacha20poly1305::aead::{Aead, AeadCore, KeyInit, OsRng, Payload};
use chacha20poly1305::{Key, XChaCha20Poly1305, XNonce};
use hkdf::Hkdf;
use sha2::Sha256;
use x25519_dalek::{EphemeralSecret, PublicKey, StaticSecret};
use zeroize::Zeroizing;

/// The HKDF `info` binding the derived key to this exact use — so the same ECDH output, reused
/// nowhere else in this codebase, could never collide with a different protocol's key.
const INFO: &[u8] = b"adi-byo-credentials-lease-seal-v1";

/// `adi-app`'s own session half of the ECDH, minted once at boot (`docs/byo-credentials.md` §9).
/// Never serialized, never written to disk — a restart simply mints a new one, which is the
/// whole mechanism behind "a server restart drops every lease".
pub struct SessionKey {
    secret: StaticSecret,
    public: [u8; 32],
    /// A random token distinguishing this boot's key from any other's — what a device's renew
    /// call presents back so `adi-app` can say "unknown epoch, re-unlock" after a restart rather
    /// than silently misattributing a renew to a lease that no longer exists.
    epoch: String,
}

/// `StaticSecret` has no `Debug` of its own (secret-key material never should), and the public
/// half and epoch are not secrets — worth printing on their own. Deliberately not
/// `finish_non_exhaustive`: that still names the field it's hiding, and a clippy pedantic warning
/// about an incomplete `Debug` here is the one time "incomplete" is the point.
#[allow(clippy::missing_fields_in_debug)]
impl std::fmt::Debug for SessionKey {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("SessionKey")
            .field("public", &hex::encode(self.public))
            .field("epoch", &self.epoch)
            .finish()
    }
}

impl SessionKey {
    /// Mint a fresh session key and epoch.
    #[must_use]
    pub fn generate() -> Self {
        let secret = StaticSecret::random_from_rng(OsRng);
        let public = PublicKey::from(&secret);
        Self {
            secret,
            public: *public.as_bytes(),
            epoch: random_epoch(),
        }
    }

    /// This boot's public key — what `GET /api/leases/session` hands the device.
    #[must_use]
    pub fn public(&self) -> [u8; 32] {
        self.public
    }

    /// This boot's epoch token.
    #[must_use]
    pub fn epoch(&self) -> &str {
        &self.epoch
    }

    /// Does `candidate` match this boot's epoch? What a renew call checks before touching the
    /// lease table at all.
    #[must_use]
    pub fn is_current_epoch(&self, candidate: &str) -> bool {
        candidate == self.epoch
    }
}

/// A random epoch token: 128 bits, hex — large enough that two boots never collide, with no
/// requirement to be unguessable (unlike the device key or a DEK, it binds no secret; it only
/// distinguishes one boot's session key from another's).
fn random_epoch() -> String {
    use rand::TryRng as _;
    let mut bytes = [0u8; 16];
    rand::rngs::SysRng
        .try_fill_bytes(&mut bytes)
        .expect("the OS random source is unavailable");
    hex::encode(bytes)
}

/// One value, sealed by the device to the session's public key — what the device sends back in
/// `POST /api/leases/unlock`'s `sealed[]`.
#[derive(Debug, Clone)]
pub struct Sealed {
    /// This call's fresh ephemeral public key — the device's own ECDH half.
    pub device_public: [u8; 32],
    pub nonce: String,
    pub ciphertext: String,
}

/// Seal `plaintext` to `session_public`, bound to `aad` — the device side. A fresh ephemeral
/// keypair every call; nothing here is reused across two calls, by construction.
///
/// # Errors
/// [`anyhow::Error`] if the underlying AEAD call fails (not expected to happen in practice).
pub fn seal(session_public: &[u8; 32], aad: &str, plaintext: &[u8]) -> anyhow::Result<Sealed> {
    let device_secret = EphemeralSecret::random_from_rng(OsRng);
    let device_public = PublicKey::from(&device_secret);
    let shared = device_secret.diffie_hellman(&PublicKey::from(*session_public));
    let key = derive_key(shared.as_bytes());

    let cipher = XChaCha20Poly1305::new(Key::from_slice(key.as_slice()));
    let nonce = XChaCha20Poly1305::generate_nonce(&mut OsRng);
    let ciphertext = cipher
        .encrypt(
            &nonce,
            Payload {
                msg: plaintext,
                aad: aad.as_bytes(),
            },
        )
        .map_err(|_| anyhow::anyhow!("sealing to the session key failed"))?;

    let b64 = base64::engine::general_purpose::STANDARD;
    Ok(Sealed {
        device_public: *device_public.as_bytes(),
        nonce: b64.encode(nonce.as_slice()),
        ciphertext: b64.encode(ciphertext),
    })
}

/// Open a value sealed by [`seal`] to this session — the server side. Fails on a wrong AAD (the
/// caller's own job to build correctly — see this module's header), a tampered ciphertext, or a
/// `device_public` that doesn't match the keypair the sealing side used.
///
/// # Errors
/// [`anyhow::Error`] on any decode or decrypt failure — deliberately not distinguished further,
/// since every cause looks the same to a caller ("this didn't open") and none should be
/// diagnosable from the outside.
pub fn open(
    session: &SessionKey,
    device_public: &[u8; 32],
    aad: &str,
    nonce_b64: &str,
    ciphertext_b64: &str,
) -> anyhow::Result<Zeroizing<Vec<u8>>> {
    let b64 = base64::engine::general_purpose::STANDARD;
    let shared = session
        .secret
        .diffie_hellman(&PublicKey::from(*device_public));
    let key = derive_key(shared.as_bytes());

    let nonce_bytes = b64.decode(nonce_b64)?;
    anyhow::ensure!(nonce_bytes.len() == 24, "bad nonce length");
    let ciphertext = b64.decode(ciphertext_b64)?;

    let cipher = XChaCha20Poly1305::new(Key::from_slice(key.as_slice()));
    let plaintext = cipher
        .decrypt(
            XNonce::from_slice(&nonce_bytes),
            Payload {
                msg: &ciphertext,
                aad: aad.as_bytes(),
            },
        )
        .map_err(|_| anyhow::anyhow!("could not open the sealed value"))?;
    Ok(Zeroizing::new(plaintext))
}

/// HKDF-SHA256 the raw ECDH output into a 32-byte AEAD key, bound to [`INFO`] so this exact
/// derivation can never be reused as the key for a different protocol by accident.
fn derive_key(shared_secret: &[u8; 32]) -> Zeroizing<[u8; 32]> {
    let hk = Hkdf::<Sha256>::new(None, shared_secret);
    let mut key = Zeroizing::new([0u8; 32]);
    hk.expand(INFO, key.as_mut())
        .expect("32 bytes is a valid HKDF-SHA256 output length");
    key
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn a_value_sealed_to_the_session_opens_with_its_secret() {
        let session = SessionKey::generate();
        let sealed = seal(&session.public(), "user:u-aaa/K|epoch1|device1", b"sk-mine").expect("seal");
        let opened = open(
            &session,
            &sealed.device_public,
            "user:u-aaa/K|epoch1|device1",
            &sealed.nonce,
            &sealed.ciphertext,
        )
        .expect("open");
        assert_eq!(&*opened, b"sk-mine");
    }

    #[test]
    fn a_mismatched_aad_fails_to_open() {
        let session = SessionKey::generate();
        let sealed = seal(&session.public(), "user:u-aaa/K|epoch1|device1", b"v").expect("seal");
        assert!(
            open(
                &session,
                &sealed.device_public,
                "user:u-bbb/K|epoch1|device1",
                &sealed.nonce,
                &sealed.ciphertext,
            )
            .is_err(),
            "a different claimed user must not open"
        );
        assert!(
            open(
                &session,
                &sealed.device_public,
                "user:u-aaa/K|epoch2|device1",
                &sealed.nonce,
                &sealed.ciphertext,
            )
            .is_err(),
            "a stale epoch must not open"
        );
    }

    #[test]
    fn a_different_session_key_cannot_open_it() {
        let session_a = SessionKey::generate();
        let session_b = SessionKey::generate();
        let sealed = seal(&session_a.public(), "aad", b"v").expect("seal");
        assert!(open(&session_b, &sealed.device_public, "aad", &sealed.nonce, &sealed.ciphertext).is_err());
    }

    #[test]
    fn two_seals_of_the_same_value_use_different_device_keys_and_ciphertexts() {
        let session = SessionKey::generate();
        let first = seal(&session.public(), "aad", b"v").expect("seal 1");
        let second = seal(&session.public(), "aad", b"v").expect("seal 2");
        assert_ne!(first.device_public, second.device_public, "fresh ephemeral key each call");
        assert_ne!(first.ciphertext, second.ciphertext);
    }

    #[test]
    fn two_generated_sessions_have_different_epochs_and_keys() {
        let a = SessionKey::generate();
        let b = SessionKey::generate();
        assert_ne!(a.epoch(), b.epoch());
        assert_ne!(a.public(), b.public());
        assert!(a.is_current_epoch(a.epoch()));
        assert!(!a.is_current_epoch(b.epoch()));
    }
}
